// FLOW-23 BI 导入（PAGE-F09-01 · BI 双月）：整份拒绝 → 修正后覆盖导入 → 新老品归集。期望值逐字取自契约 FLOW-23。
import { BASE, check, eq, fileOf, loginAs, run, tableText } from './_e3_harness.mjs'

await run('FLOW-23', 'flow23', '2027-05-06 14:00', async (env) => {
  const f = env.seeded
  const page = await env.newPage()
  await loginAs(page, '陈思雨')
  await page.goto(`${BASE}/actuals/import`)
  const root = page.locator('[data-page-id="PAGE-F09-01"]')
  await root.locator('.tab', { hasText: 'BI 双月' }).click()

  await root.locator('input[type=file]').setInputFiles(fileOf(f.bad))
  await root.getByRole('button', { name: '上传并校验' }).click()
  await root.locator('#fail-t').waitFor({ timeout: 60000 })
  const notice = await root.locator('section[aria-labelledby="fail-t"] .notice').textContent()
  check(notice.includes('校验未通过，本文件没有写入任何数据。'), '首次上传整份不写入')
  check(notice.includes('2 个 SKU 不在 SKU 对照表中'), '未映射 SKU 共 2 个')
  const issues = (await tableText(root.locator('section[aria-labelledby="fail-t"] table'))).slice(1)
  console.log('  问题行：', JSON.stringify(issues))
  const skus = issues.filter((r) => r[1] === 'SKU 未映射').map((r) => r[2]).sort()
  eq(skus, ['BT-1701-WH', 'SD-9999-XX'], '列出全部未映射 SKU')
  check(issues.some((r) => r[0] === '第 40 行' && r[1] === '月份格式错误' && r[2] === '2027-4'), '第 40 行月份「2027-4」')
  check(issues.some((r) => r[0] === '第 41 行' && r[1] === '站点不在主数据中' && r[2] === '墨西哥'), '第 41 行站点「墨西哥」')
  let recs = (await tableText(root.locator('section[aria-labelledby="rec-t"] table'))).slice(1)
  eq(recs.length, 1, '失败的上传不写入（导入记录仍只有原 BI 批次）')

  await root.locator('input[type=file]').setInputFiles(fileOf(f.fixed))
  await root.getByRole('button', { name: '上传并校验' }).click()
  await root.locator('#pass-t').waitFor({ timeout: 60000 })
  const warn = await root.locator('section[aria-labelledby="pass-t"] .notice.warn').textContent()
  check(warn.includes('2027-03 已有导入数据：BI_2027-03_销售明细.xlsx（陈思雨，2027-04-20 09:30）'), `覆盖前列出受影响月份与旧批次文件名、导入人、时间：${warn.trim()}`)
  const preview = (await tableText(root.locator('section[aria-labelledby="pass-t"] .card').nth(1).locator('table'))).slice(1)
  console.log('  归集预览：', JSON.stringify(preview))
  check(preview.some((r) => r[0] === '2027-02' && r[1] === 'Amazon-US-01 · 美国' && r[2] === '框镜' && r[3] === '新品'), 'FM-2416-WH 2027-02 → 2027-02 × Amazon-US-01 × 美国 × 框镜 × 新品')
  check(preview.some((r) => r[0] === '2027-03' && r[1] === 'Amazon-US-01 · 美国' && r[2] === '框镜' && r[3] === '老品'), 'FM-2416-WH 2027-03 → 2027-03 × Amazon-US-01 × 美国 × 框镜 × 老品')
  await root.getByRole('button', { name: '确认覆盖导入' }).click()
  await page.getByRole('button', { name: '确认覆盖', exact: true }).click()
  await root.locator('.toast').waitFor({ timeout: 60000 })
  await page.waitForTimeout(500)
  recs = (await tableText(root.locator('section[aria-labelledby="rec-t"] table'))).slice(1)
  console.log('  导入记录：', JSON.stringify(recs))
  const old = recs.find((r) => r[2] === 'BI_2027-03_销售明细.xlsx')
  check(!!old && old[4] === '陈思雨' && old[5] === '2027-04-20 09:30' && old[6].startsWith('已被替换'), '旧 BI 批次「已被替换」且记录保留')
})

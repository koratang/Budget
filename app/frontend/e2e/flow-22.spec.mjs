// FLOW-22 金蝶月度导入（PAGE-F09-01）：整份拒绝 → 修正后覆盖导入 → 未归属渠道 → 24 个月历史。期望值逐字取自契约 FLOW-22。
import { BASE, check, eq, fileOf, loginAs, run, tableText } from './_e3_harness.mjs'

await run('FLOW-22', 'flow22', '2027-05-12 10:00', async (env) => {
  const f = env.seeded
  const page = await env.newPage()
  await loginAs(page, '陈思雨')
  await page.goto(`${BASE}/actuals/import`)
  const root = page.locator('[data-page-id="PAGE-F09-01"]')
  await root.locator('.tab', { hasText: '金蝶月度' }).click()

  // 1. 含 4 个问题行的文件
  await root.locator('input[type=file]').setInputFiles(fileOf(f.v2))
  await root.getByRole('button', { name: '上传并校验' }).click()
  await root.locator('#fail-t').waitFor({ timeout: 60000 })
  eq(await root.locator('#fail-t').textContent(), '校验未通过，本文件没有写入任何数据。', '首次上传显示「校验未通过，本文件没有写入任何数据。」')
  const issues = (await tableText(root.locator('section[aria-labelledby="fail-t"] table'))).slice(1)
  console.log('  问题行：', JSON.stringify(issues))
  eq(issues.map((r) => r[0]), ['第 7 行', '第 15 行', '第 22 行', '第 31 行'], '列出 4 行（行号）')
  eq(issues.map((r) => r[1]), ['期间格式错误', '部门不在主数据中', '店铺不在主数据中', '金蝶科目未映射'], '各行问题类型')
  check(issues[0]?.[2] === '2027/4' && issues[1]?.[2] === '视觉二部' && issues[2]?.[2] === 'Amazon-MX-01' && issues[3]?.[2].includes('6601.99'), '各行涉及编码或名称')
  let recs = (await tableText(root.locator('section[aria-labelledby="rec-t"] table'))).slice(1)
  eq(recs.length, 1, '失败的上传不产生导入记录（业务数据未写入）')

  // 2. 修正后上传：覆盖提示原文件名、导入人、时间 → 确认覆盖
  await root.locator('input[type=file]').setInputFiles(fileOf(f.v3))
  await root.getByRole('button', { name: '上传并校验' }).click()
  await root.locator('#pass-t').waitFor({ timeout: 60000 })
  const warn = await root.locator('section[aria-labelledby="pass-t"] .notice.warn').textContent()
  check(warn.includes('金蝶_2027-04_利润表.xlsx（陈思雨，2027-05-10 16:42）'), `覆盖前提示原文件名、导入人、时间：${warn.trim()}`)
  const unassigned = await tableText(root.locator('section[aria-labelledby="pass-t"] .card').nth(1).locator('table'))
  console.log('  未归属渠道：', JSON.stringify(unassigned))
  check(unassigned.some((r) => r[0].startsWith('6601.06') && r[2] === '¥ 12,000.00'), '仓储杂费 12,000.00 计入未归属渠道')
  await root.getByRole('button', { name: '确认覆盖导入' }).click()
  await page.getByRole('button', { name: '确认覆盖', exact: true }).click()
  await root.locator('.toast').waitFor({ timeout: 60000 })
  await page.waitForTimeout(500)
  recs = (await tableText(root.locator('section[aria-labelledby="rec-t"] table'))).slice(1)
  console.log('  导入记录：', JSON.stringify(recs))
  const old = recs.find((r) => r[2] === '金蝶_2027-04_利润表.xlsx')
  check(!!old && old[4] === '陈思雨' && old[5] === '2027-05-10 16:42' && old[6].startsWith('已被替换'), '原批次「已被替换」并保留文件名、导入人、导入时间')
  const neu = recs.find((r) => r[2] === '金蝶_2027-04_利润表_v3.xlsx')
  check(!!neu && neu[6].startsWith('生效'), '新批次生效')

  // 3. 12,000.00 在渠道×站点偏差「未归属渠道」单列
  await page.context().clearCookies()
  await loginAs(page, '林晓')
  await page.goto(`${BASE}/reports/channel?month=2027-04`)
  await page.locator('[data-page-id="PAGE-F10-02"] table').first().waitFor()
  await page.waitForTimeout(500)
  const rep = await tableText(page.locator('[data-page-id="PAGE-F10-02"] table').first())
  const un = rep.find((r) => r[0].startsWith('未归属渠道'))
  console.log('  未归属渠道行：', JSON.stringify(un))
  check(!!un && un.some((c) => c.includes('12,000.00')), '渠道×站点偏差「未归属渠道」单列 12,000.00')

  // 4. 历史文件 24 个期间逐月入库
  await page.context().clearCookies()
  await loginAs(page, '陈思雨')
  await page.goto(`${BASE}/actuals/import`)
  await root.locator('.tab', { hasText: '历史金蝶' }).click()
  await root.locator('input[type=file]').setInputFiles(fileOf(f.history))
  await root.getByRole('button', { name: '上传并校验' }).click()
  await root.locator('#pass-t').waitFor({ timeout: 60000 })
  const summary = await root.locator('section[aria-labelledby="pass-t"] dl').textContent()
  check(summary.includes('2025-01 至 2026-12（24 个期间）'), '历史文件识别 24 个期间')
  await root.getByRole('button', { name: /^确认导入$/ }).click()
  await root.locator('.toast').waitFor({ timeout: 60000 })
  await page.waitForTimeout(500)
  const cells = await root.locator('section[aria-labelledby="his-t"] .months > div').allTextContents()
  eq(cells.length, 24, '历史网格 24 格')
  check(cells.every((c) => c.includes('已入库')), '历史网格 24 格均为已入库')
  const foot = await root.locator('section[aria-labelledby="his-t"] p').textContent()
  check(foot.includes('已入库 24 / 24'), '已入库 24 / 24')
  await page.screenshot({ path: '/tmp/e3_acc/flow-22-history.png', fullPage: true })
})

// FLOW-27 公司汇总（PAGE-F10-01）与工作台（PAGE-F00-01）：达成率双口径、增速对比、预测准确度。期望值逐字取自契约 FLOW-27。
import { BASE, check, eq, loginAs, py, run, tableText } from './_e3_harness.mjs'

await run('FLOW-27', 'flow27', '2027-05-20 10:00', async (env) => {
  const page = await env.newPage()
  await loginAs(page, '林晓')
  await page.goto(`${BASE}/reports/company`)
  const root = page.locator('[data-page-id="PAGE-F10-01"]')
  await root.locator('[data-testid="kpi-original"]').waitFor()
  await page.waitForTimeout(500)
  eq((await root.locator('[data-testid="kpi-original"] .kpi-value').textContent()).trim(), '90.0%', '公司汇总原始口径 90.0%')
  eq((await root.locator('[data-testid="kpi-adjusted"] .kpi-value').textContent()).trim(), '96.0%', '公司汇总调整后口径 96.0%')
  const g = root.locator('.growth-cmp')
  const gtext = (await g.locator('.kpi-value').allTextContents()).map((s) => s.trim())
  console.log('  增速：', JSON.stringify(gtext))
  eq(gtext[0], '+12.0%', '收入增速 +12.0%')
  eq(gtext[1], '+16.0%', '部门费用增速 +16.0%')
  check(await g.locator('.kpi-value').nth(1).evaluate((e) => e.classList.contains('bad')), '费用增速标红')
  const acc = (await tableText(root.locator('section').filter({ hasText: '快照预测净利润率' }).locator('table').first())).slice(1)
  console.log('  预测准确度：', JSON.stringify(acc))
  const apr = acc.find((r) => r[0] === '2027-04')
  const mar = acc.find((r) => r[0] === '2027-03')
  check(apr[2] === '5.00%' && apr[3] === '3.33%' && apr[4] === '1.67' && apr[5] === '超阈值', '2027-04 预测偏差 = 5.00 − 3.33 = 1.67 个百分点标红')
  const accTable = root.locator('section').filter({ hasText: '快照预测净利润率' }).locator('table').first()
  const aprBad = await accTable.locator('tbody tr', { hasText: '2027-04' }).locator('td.bad').count()
  const marBad = await accTable.locator('tbody tr', { hasText: '2027-03' }).locator('td.bad').count()
  eq(marBad, 0, '2027-03 偏差单元格不标红')
  check(aprBad === 1, '2027-04 偏差单元格标红')
  check(mar[2] === '5.00%' && mar[3] === '4.20%' && mar[4] === '0.80' && mar[5] === '未超', '2027-03 为 0.80 个百分点不标红')

  await page.goto(`${BASE}/`)
  const wb = page.locator('[data-page-id="PAGE-F00-01"]')
  await wb.locator('[data-testid="kpi-original"]').waitFor()
  await page.waitForTimeout(500)
  eq((await wb.locator('[data-testid="kpi-original"] .kpi-value').textContent()).trim(), '90.0%', '工作台原始口径 90.0%')
  eq((await wb.locator('[data-testid="kpi-adjusted"] .kpi-value').textContent()).trim(), '96.0%', '工作台调整后口径 96.0%')

  // 另造一年度（2028）同期目标合计 −50,000.00，上年同期（2027-05）未导入
  py('add', 'flow27-2028')
  await page.goto(`${BASE}/reports/company`)
  await root.locator('[data-testid="kpi-original"]').waitFor()
  await page.waitForTimeout(500)
  check((await root.locator('.meta').first().textContent()).includes('预算年度 2028'), '公司汇总切到 2028 年度')
  eq((await root.locator('[data-testid="kpi-original"] .kpi-value').textContent()).trim(), '—', '目标合计 ≤ 0 时显示「—」（原始口径）')
  eq((await root.locator('[data-testid="kpi-adjusted"] .kpi-value').textContent()).trim(), '—', '目标合计 ≤ 0 时显示「—」（调整后口径）')
  check((await root.textContent()).includes('上年同期实际未导入，暂不计算增速'), '上年同期未导入时显示「上年同期实际未导入，暂不计算增速」')
  await page.goto(`${BASE}/`)
  await wb.locator('[data-testid="kpi-original"]').waitFor()
  await page.waitForTimeout(500)
  eq((await wb.locator('[data-testid="kpi-original"] .kpi-value').textContent()).trim(), '—', '工作台目标合计 ≤ 0 时显示「—」')

  // 回归：编制期页头「预算年度」显示正在编制的年度（关键数仍按报告年度 2028）
  py('add', 'compiling-2029')
  await page.goto(`${BASE}/`)
  await wb.locator('[data-testid="kpi-original"]').waitFor()
  await page.waitForTimeout(500)
  const meta = await wb.locator('.wb-head .meta').textContent()
  check(meta.includes('预算年度 2029') && meta.includes('最近金蝶导入期间 2028-05'), `编制期页头显示正在编制的年度：${meta.trim()}`)
})
